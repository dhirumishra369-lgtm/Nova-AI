# --- CLEAN SIMULATION ENGINE ---
def get_response(user_text):
    text_lower = user_text.lower().strip()
    
    # Image trigger check
    if any(w in text_lower for w in ["pic", "photo", "image", "bano", "banao", "draw", "generate", "design", "dikhao", "ganesh", "shiv"]):
        query = text_lower.replace("pic", "").replace("photo", "").replace("image", "").replace("bano", "").replace("banao", "").replace("dikhao", "").strip()
        if not query:
            query = text_lower
        encoded = urllib.parse.quote(query)
        image_link = "https://source.unsplash.com/featured/600x400/?" + encoded
        msg = "🎨 Aapki mangi gayi tasveer yahan taiyar ki gayi hai:"
        return msg, image_link
    
    # General response
    elif "kaun ho" in text_lower or "who are you" in text_lower:
        msg = "Main **Navo Ultra Super Fast AI** hoon, jise **Dhirendra Mishra** dwara banaya gaya hai. Main aapki har tarah ki madad karne ke liye taiyar hoon!"
        return msg, None
    else:
        msg = "Aapka sawal mil gaya hai. Navo AI engine is par vichar kar raha hai aur aapko ekdam sateek jawab de raha hai. Ismein aur kya janna chahte hain?"
        return msg, None

# --- CHAT INPUT & HANDLER ---
if prompt := st.chat_input("Kuch bhi puchiye ya pic banane ko kahiye..."):
    st.session_state.messages.append({"role": "user", "content": prompt})
    with st.chat_message("user"):
        st.markdown(prompt)

    reply_text, img_link = get_response(prompt)

    msg_data = {"role": "assistant", "content": reply_text, "img_url": img_link}
    st.session_state.messages.append(msg_data)

    with st.chat_message("assistant"):
        st.markdown(reply_text)
        if img_link:
            st.image(img_link, caption="Generated by Navo AI", use_container_width=True)
